import { expect, test } from '@playwright/test';
import { panel, setupWorkFolder } from './helpers';
import { chooseFn, currentNode, graphOf, nodeOf, prepareEdit, reopenEdit, startEditResult } from './edit-helpers';

test.beforeAll(async ({ playwright }) => { await setupWorkFolder(playwright); });

test('掩码涂抹、撤销重做、刷新保留；羽化与强度进入实际工作流', async ({ page }, testInfo) => {
  await prepareEdit(page, '持久掩码');
  await chooseFn(page, 'inpaint');
  await panel(page).locator('#wbText').fill('red jacket');
  await panel(page).locator('#editStart').click();
  await expect(panel(page).locator('#editDockError')).toContainText('掩码');
  await panel(page).locator('#wbMaskEditor').click();
  const dialog = page.getByRole('dialog', { name: '局部重绘掩码' });
  const canvas = dialog.locator('canvas');
  await expect(canvas).toBeVisible();
  const box = (await canvas.boundingBox())!;
  await page.mouse.move(box.x + box.width * 0.3, box.y + box.height * 0.3);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * 0.6, box.y + box.height * 0.6, { steps: 10 });
  await page.mouse.up();
  await dialog.locator('#maskUndo').click();
  await expect(dialog.getByRole('button', { name: '保存掩码' })).toBeDisabled();
  await dialog.locator('#maskRedo').click();
  await expect(dialog.getByRole('button', { name: '保存掩码' })).toBeEnabled();
  await canvas.focus();
  await page.keyboard.press('Control+z');
  await expect(dialog.getByRole('button', { name: '保存掩码' })).toBeDisabled();
  await page.keyboard.press('Control+Shift+z');
  await expect(dialog.getByRole('button', { name: '保存掩码' })).toBeEnabled();
  await dialog.getByRole('button', { name: '保存掩码' }).click();
  await expect(dialog).toHaveCount(0);
  await panel(page).locator('#wbFeather').fill('64');
  await panel(page).locator('#wbDenoise').fill('0.85');
  await expect.poll(async () => (await currentNode(page)).edit?.maskShapes?.strokes.length).toBe(1);
  await expect.poll(async () => (await currentNode(page)).edit?.inpaint).toMatchObject({ feather: 64, denoise: 0.85 });
  await reopenEdit(page);
  await expect(panel(page).locator('#editPane-execute')).toContainText('掩码已保存');
  await expect(panel(page).locator('#wbFeather')).toHaveValue('64');
  await startEditResult(page);
  const graph = await graphOf(page);
  expect(nodeOf(graph, 'InpaintCropImproved').inputs.mask_blend_pixels).toBe(64);
  expect(nodeOf(graph, 'KSampler').inputs.denoise).toBe(0.85);
  expect(Object.values(graph).filter((n) => n.class_type === 'LoadImage')).toHaveLength(2);
  await page.screenshot({ path: testInfo.outputPath('inpaint-result.png') });
});
